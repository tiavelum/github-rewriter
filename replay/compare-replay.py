#!/usr/bin/env python3
"""Compares a finished replay with its source, read-only: the items, labels,
bodies, comments, the reviews the replay carries as comments, the default
branch, the branches, tags and releases of the target against those of the
source, the event file and the state file of run-replay.py; each tag the
event file carries at the recreated commit, lightweight or annotated as
planned, an annotated one with the planned message, tagger and date; each
release it carries, as the state file maps it to the target's, under its
tag, with the planned name, body, kind and latest, and the source's assets by
name, size, content type and digest. A branch, tag or release of the
source that the target lacks is a note where the event file's header lists
it as left behind, and a difference otherwise. Where the header lists tags,
releases or reviews as turned off, it notes that instead, and names any of
them the target holds a difference. The source's default branch is compared
with the target's under the name the plan gives it, main for master, and the
target's default branch has to be that one.

  compare-replay.py [--with-times] [--state <file>] <event file> <mirror> <owner/repo>

<event file> and <mirror> are those run-replay.py applied; <owner/repo> is
the target. The state file is <event file> with .state.json for .jsonl
unless --state names one; it gives the map of source to target commits and
releases and the --final-name of the run. Give --with-times where the run
had it.

Reads GitHub through gh api with GET requests only, and the target's commits
with git fetch into a temporary repository that borrows the mirror's objects.
Prints the totals, any notes and every difference; exits with 1 where there
is a difference, with 0 where there is none, and with 2 where it cannot
compare, as where the state file records the replay unfinished or belongs to
another event file or target. The notes, which are no differences, name the
renamed default branch, who authored the merges, each branch the target
keeps that the source no longer has, each tag, release and branch the plan
left behind or turned off, and an event file planned before its header
recorded what it leaves behind, which then accepts nothing as left behind.

It cannot see the source's secrets, variables, webhooks, deploy keys and
collaborators; check those yourself before the source is archived.
"""

import bisect
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

PROG = "compare-replay.py"
FORMAT = 1
STATE_FORMAT = 1
SLUG = re.compile(r"[\w.-]+/[\w.-]+")
HASH = re.compile(r"(?<![0-9A-Za-z])[0-9a-f]{7,40}(?![0-9A-Za-z])")
CO_AUTHOR = re.compile(r"co-authored-by:", re.IGNORECASE)
# The footer a Claude session's access to GitHub appends to a body it creates.
FOOTER = re.compile(r"\n---\n+_Generated by \[Claude Code\]\([^)]*\)_\s*$")
IDENTITY = re.compile(r"^(?P<name>.*) <(?P<email>[^>]*)> (?P<date>\d+ [+-]\d{4})$")
# git takes the last of these lines in a signed tag's message as the start of its signature.
SIGNATURE = re.compile(
    r"^-----BEGIN (PGP SIGNATURE|PGP MESSAGE|SIGNED MESSAGE|SSH SIGNATURE)-----$", re.M
)


def unsigned(message):
    # Only where the text from the last opening line on ends with its closing
    # line: a message may hold such a line in its text.
    starts = list(SIGNATURE.finditer(message))
    if starts and message.rstrip("\n").endswith(f"-----END {starts[-1].group(1)}-----"):
        return message[: starts[-1].start()]
    return message


class CompareError(Exception):
    pass


def usage(status=2):
    print(__doc__.strip("\n"), file=sys.stderr if status else sys.stdout)
    sys.exit(status)


def run(args, stdin=None):
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0"}
    # Bytes, not text mode, which turns "\r\n" and a lone "\r" of a message into "\n".
    try:
        result = subprocess.run(
            args,
            input=None if stdin is None else stdin.encode("utf-8"),
            stdin=subprocess.DEVNULL if stdin is None else None,
            capture_output=True,
            env=env,
        )
    except FileNotFoundError:
        raise CompareError(f"{args[0]} is missing") from None
    result.stdout = result.stdout.decode("utf-8", errors="replace")
    result.stderr = result.stderr.decode("utf-8", errors="replace")
    return result


def git(repo, *args, stdin=None):
    result = run(["git", "-C", str(repo), *args], stdin)
    if result.returncode:
        raise CompareError(f"git {args[0]} failed: {result.stderr.strip()}")
    return result.stdout


def gh_get(endpoint):
    result = run(["gh", "api", endpoint])
    if result.returncode:
        error = result.stderr.strip().splitlines()
        raise CompareError(f"gh api {endpoint} failed: {error[-1] if error else ''}")
    return json.loads(result.stdout)


def gh_pages(endpoint):
    # Read up to the first empty page, since gh's --paginate fails through some proxies.
    joiner = "&" if "?" in endpoint else "?"
    entries, page = [], 1
    while True:
        batch = gh_get(f"{endpoint}{joiner}per_page=100&page={page}")
        if not batch:
            return entries
        entries.extend(batch)
        page += 1


def gh_found(endpoint):
    result = run(["gh", "api", endpoint])
    if result.returncode == 0:
        return json.loads(result.stdout)
    if "(HTTP 404)" in result.stderr:
        return None
    error = result.stderr.strip().splitlines()
    raise CompareError(f"gh api {endpoint} failed: {error[-1] if error else ''}")


def git_date(stamp):
    moment = datetime.fromisoformat(stamp.replace("Z", "+00:00"))
    minutes = int(moment.utcoffset().total_seconds()) // 60
    sign = "-" if minutes < 0 else "+"
    return f"{int(moment.timestamp())} {sign}{abs(minutes) // 60:02}{abs(minutes) % 60:02}"


def utc_text(stamp):
    moment = datetime.fromisoformat(stamp.replace("Z", "+00:00")).astimezone(timezone.utc)
    return moment.strftime("%Y-%m-%d %H:%M UTC")


def release_label(e, carried):
    what = "draft" if e["draft"] else "pre-release" if e["prerelease"] else "published"
    shared = sum(x["tag_name"] == e["tag_name"] for x in carried) > 1
    return f"release {e['tag_name']}" + (f" ({what})" if shared else "")


def default_state_path(events_path):
    name = events_path.name
    stem = name[: -len(".jsonl")] if name.endswith(".jsonl") else name
    return events_path.with_name(stem + ".state.json")


def where_texts_part(expected, found):
    if FOOTER.search(found) and not FOOTER.search(expected):
        return "it has a footer the source lacks"
    i = next(
        (k for k, (a, b) in enumerate(zip(expected, found, strict=False)) if a != b),
        min(len(expected), len(found)),
    )
    return (
        f"they part at character {i + 1}:"
        f" {found[max(0, i - 20) : i + 40]!r}, the source's {expected[max(0, i - 20) : i + 40]!r}"
    )


def without_added_trailers(message, planned):
    # GitHub appends Co-authored-by lines to the message of a merge.
    # Split at "\n" alone, as the message below, so that a line ending in "\r" stays known.
    known = set(planned.split("\n"))
    lines = message.rstrip("\n").split("\n")
    while lines and (lines[-1] == "" or (CO_AUTHOR.match(lines[-1]) and lines[-1] not in known)):
        lines.pop()
    return "\n".join(lines)


def item_number(comment):
    return int(comment["issue_url"].rsplit("/", 1)[1])


def peeled_refs(repo, *prefixes):
    # Only a newline ends a name: git allows other Unicode blanks in one.
    out = git(repo, "for-each-ref", "--format=%(refname)", *prefixes)
    names = [name for name in out.split("\n") if name]
    # A tag of a tag peels one level in %(*objectname), so peel with ^{}.
    peeled = git(
        repo,
        "cat-file",
        "--batch-check=%(objectname)",
        stdin="".join(f"{name}^{{}}\n" for name in names),
    ).split()
    return dict(zip(names, peeled, strict=True))


def read_commits(repo, shas):
    try:
        out = subprocess.run(
            ["git", "-C", str(repo), "cat-file", "--batch"],
            input="".join(f"{s}\n" for s in shas).encode(),
            capture_output=True,
        )
    except FileNotFoundError:
        raise CompareError("git is missing") from None
    if out.returncode:
        raise CompareError(f"git cat-file failed: {out.stderr.decode(errors='replace').strip()}")
    data, found, at = out.stdout, {}, 0
    for sha in shas:
        end = data.index(b"\n", at)
        header = data[at:end].decode().split()
        at = end + 1
        if header[-1] == "missing":
            continue
        size = int(header[2])
        body, at = data[at : at + size].decode("utf-8", errors="replace"), at + size + 1
        if header[1] != "commit":
            continue
        head, _, message = body.partition("\n\n")
        info = {"parents": [], "message": message}
        for line in head.split("\n"):
            key, _, value = line.partition(" ")
            if key == "tree":
                info["tree"] = value
            elif key == "parent":
                info["parents"].append(value)
            elif key in ("author", "committer"):
                match = IDENTITY.match(value)
                info[key] = match.groupdict() if match else {"name": value}
        found[sha] = info
    return found


class Comparison:
    def __init__(self, events_path, mirror, slug, state_path, with_times):
        self.mirror, self.slug, self.with_times = mirror, slug, with_times
        raw = events_path.read_bytes()
        try:
            lines = [json.loads(x) for x in raw.decode("utf-8").splitlines() if x.strip()]
        except ValueError as error:
            raise CompareError(f"{events_path} is no event file: {error}") from None
        if not lines or lines[0].get("kind") != "header" or lines[0].get("format") != FORMAT:
            raise CompareError(f"{events_path} has no header of format {FORMAT}")
        self.header, self.events = lines[0], lines[1:]
        self.source, self.default = self.header["source"], self.header["default_branch"]
        # An event file planned before the rename of master to main names only the source's.
        self.target_default = self.header.get("target_default_branch", self.default)
        # Missing in an event file planned before the switches, which turned nothing off.
        self.turned_off = set(self.header.get("turned_off", []))
        try:
            state = json.loads(state_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            raise CompareError(f"cannot read the state file {state_path}: {error}") from None
        if (
            state.get("format") != STATE_FORMAT
            or state.get("events") != hashlib.sha256(raw).hexdigest()
        ):
            raise CompareError(f"{state_path} belongs to another event file")
        if state.get("target") != slug:
            raise CompareError(f"{state_path} records a replay into {state.get('target')}")
        if not state.get("finished"):
            raise CompareError(
                f"{state_path} records the replay unfinished, at event {state.get('done')} of"
                f" {len(self.events)}; finish it with run-replay.py first"
            )
        self.hashes, self.final_name = state["hashes"], state.get("final_name")
        # None for a run started before committer dates were the time of the
        # replay, whose commits keep their original committer dates.
        self.committer_dates = state.get("committer_dates")
        self.heads = {int(k): v for k, v in state["heads"].items()}
        self.urls = {int(k): v for k, v in state["urls"].items()}
        # Missing in a state file written before releases were carried, whose event file plans none.
        self.releases = state.get("releases", {})
        self.sources = sorted(set(self.header["source_commits"]))
        self.differences, self.notes, self.totals = [], [], []
        self.replaced = 0

    def differ(self, text):
        self.differences.append(text)

    def text(self, value):
        # The text as run-replay.py writes it.
        if not value:
            return value or ""

        def replace(match):
            prefix = match.group(0)
            i = bisect.bisect_left(self.sources, prefix)
            found = [s for s in self.sources[i : i + 2] if s.startswith(prefix)]
            if len(found) == 1 and found[0] in self.hashes:
                return self.hashes[found[0]][: len(prefix)]
            return prefix

        return HASH.sub(replace, value)

    def expected_text(self, value, created):
        replaced = self.text(value or "")
        self.replaced += replaced != (value or "")
        if self.with_times and created:
            line = f"_Originally created {utc_text(created)}._"
            replaced = f"{replaced}\n\n{line}" if replaced else line
        return replaced

    def items(self, source_items, target_items):
        planned = {
            e["number"]: e for e in self.events if e["kind"] in ("create-issue", "create-pull")
        }
        for n in sorted(set(planned) | set(source_items) | set(target_items)):
            e, s, t = planned.get(n), source_items.get(n), target_items.get(n)
            if e is None:
                side = "the source" if s else "the target"
                self.differ(f"#{n} of {side} is not in the event file")
                continue
            if t is None:
                self.differ(f"#{n} is missing in the target")
                continue
            if s is None and not e.get("placeholder"):
                self.differ(f"#{n} is missing in the source")
                continue
            kind = "pull request" if e["kind"] == "create-pull" else "issue"
            found = "pull request" if "pull_request" in t else "issue"
            if found != kind:
                self.differ(f"#{n} is a {found}, the source's a {kind}")
                continue
            if t["title"] != self.text(e["title"]):
                self.differ(f"#{n}: title {t['title']!r}, planned {self.text(e['title'])!r}")
            if s is None:
                want = {"state": "closed", "reason": "not_planned", "labels": [], "assignees": []}
                body, created = "", None
            else:
                merged = bool((s.get("pull_request") or {}).get("merged_at"))
                want = {
                    "state": "merged" if merged else s["state"],
                    "reason": s.get("state_reason"),
                    "labels": sorted(x["name"] for x in s.get("labels", [])),
                    "assignees": sorted(x["login"] for x in s.get("assignees", [])),
                }
                body, created = s.get("body"), s.get("created_at")
            merged = bool((t.get("pull_request") or {}).get("merged_at"))
            state = "merged" if merged else t["state"]
            if state != want["state"]:
                self.differ(f"#{n} is {state}, the source's {want['state']}")
            # GitHub closes an issue without a reason as completed; an open
            # issue's reason only tells whether it was ever reopened.
            elif kind == "issue" and state == "closed":
                reason = t.get("state_reason") or "completed"
                if reason != (want["reason"] or "completed"):
                    self.differ(f"#{n} is closed as {reason}, the source's {want['reason']}")
            for field in ("labels", "assignees"):
                key = "name" if field == "labels" else "login"
                got = sorted(x[key] for x in t.get(field, []))
                if got != want[field]:
                    self.differ(f"#{n}: {field} {got}, the source's {want[field]}")
            expected = self.expected_text(body, created)
            if (t.get("body") or "") != expected:
                self.differ(
                    f"#{n}: the body differs; {where_texts_part(expected, t.get('body') or '')}"
                )
        self.totals.append(("items", len(target_items)))

    def labels(self, source_labels, target_labels):
        source = {x["name"]: x for x in source_labels}
        target = {x["name"]: x for x in target_labels}
        for name in sorted(set(source) | set(target)):
            s, t = source.get(name), target.get(name)
            if s is None or t is None:
                self.differ(f"label {name} is missing in the {'target' if t is None else 'source'}")
                continue
            if (t.get("color") or "").lower() != (s.get("color") or "").lower():
                self.differ(f"label {name}: colour {t.get('color')}, the source's {s.get('color')}")
            if (t.get("description") or "") != (s.get("description") or ""):
                self.differ(
                    f"label {name}: description {t.get('description')!r},"
                    f" the source's {s.get('description')!r}"
                )
        self.totals.append(("labels", len(target_labels)))

    def comments(self, source_comments, target_comments, source_reviews):
        planned = {}
        for e in self.events:
            if e["kind"] == "add-comment":
                planned.setdefault(e["number"], []).append(e)
        events = [e for p in planned.values() for e in p]
        by_id = {c["id"]: c for c in source_comments}
        in_plan = {e.get("source_id") for e in events if "review_id" not in e}
        for c in source_comments:
            if c["id"] not in in_plan:
                self.differ(
                    f"#{item_number(c)}: comment {c['id']} of the source is not in the event file"
                )
        reviews_in_plan = {e["review_id"] for e in events if "review_id" in e}
        for rid, r in sorted((source_reviews or {}).items()):
            if rid not in reviews_in_plan:
                self.differ(f"#{r['number']}: review {rid} of the source is not in the event file")
        target = {}
        for c in sorted(target_comments, key=lambda c: c["id"]):
            target.setdefault(item_number(c), []).append(c)
        for n in sorted(set(planned) | set(target)):
            p, t = planned.get(n, []), target.get(n, [])
            if len(p) != len(t):
                self.differ(f"#{n} has {len(t)} comments, the event file plans {len(p)}")
                continue
            for i, (e, b) in enumerate(zip(p, t, strict=True), 1):
                if "review_id" in e:
                    r = (source_reviews or {}).get(e["review_id"])
                    if source_reviews is not None and r is None:
                        self.differ(f"#{n}, comment {i}: the source has no review {e['review_id']}")
                        continue
                    body = (r or {}).get("body") or ""
                    # The body follows right after the opening line, before the
                    # review comments, which could hold the same text.
                    rest = e["body"].partition("\n\n")[2]
                    if body.strip() and not rest.startswith(body):
                        self.differ(
                            f"#{n}, comment {i}: the event file lacks the body of the review"
                        )
                    expected = self.expected_text(e["body"], e.get("created_at"))
                else:
                    s = by_id.get(e.get("source_id"))
                    if s is None:
                        self.differ(
                            f"#{n}, comment {i}: the source has no comment {e.get('source_id')}"
                        )
                        continue
                    expected = self.expected_text(s.get("body"), s.get("created_at"))
                found = b.get("body") or ""
                if found != expected:
                    self.differ(
                        f"#{n}, comment {i}: the body differs; {where_texts_part(expected, found)}"
                    )
        self.totals.append(("comments", len(target_comments)))
        self.totals.append(("reviews as comments", len(reviews_in_plan)))

    def source_reviews(self):
        if "reviews" in self.turned_off:
            self.notes.append("reviews are turned off: the event file plans no review as a comment")
            return None
        if not self.header.get("reviews"):
            self.notes.append("the event file predates reviews: it plans no review as a comment")
            return None
        found = {}
        for e in self.events:
            if e["kind"] != "create-pull":
                continue
            for r in gh_pages(f"repos/{self.source}/pulls/{e['number']}/reviews"):
                # A pending review is seen only by its author, and the plan carries none.
                if r.get("state") != "PENDING" and r.get("submitted_at"):
                    found[r["id"]] = {**r, "number": e["number"]}
        return found

    def fetch(self, work, info):
        protocol = run(["gh", "config", "get", "git_protocol"]).stdout.strip()
        remote = info["ssh_url"] if protocol == "ssh" else info["clone_url"]
        objects = git(
            self.mirror, "rev-parse", "--path-format=absolute", "--git-path", "objects"
        ).strip()
        git(work.parent, "init", "-q", "--bare", work.name)
        (work / "objects" / "info" / "alternates").write_text(objects + "\n", encoding="utf-8")
        git(
            work,
            "fetch",
            "-q",
            "--no-tags",
            remote,
            "+refs/heads/*:refs/heads/*",
            "+refs/pull/*/head:refs/pull/*/head",
            "+refs/tags/*:refs/tags/*",
        )
        return peeled_refs(work, "refs/heads/", "refs/pull/", "refs/tags/")

    def pull_heads(self, refs):
        # refs/pull/<number>/head stays where the pull request's branch is deleted.
        pushed = [e["number"] for e in self.events if e["kind"] == "push-branch"]
        for n in pushed:
            sha, recorded = refs.get(f"refs/pull/{n}/head"), self.heads.get(n)
            if sha is None:
                self.differ(f"#{n}: the pull request has no head in the target")
            elif sha != recorded:
                self.differ(
                    f"#{n}: the pull request head is {sha[:7]}, the state file's"
                    f" {(recorded or '?')[:7]}"
                )
        self.totals.append(("pull request heads", len(pushed)))

    def main_branch(self, work, info):
        named = info.get("default_branch")
        if named != self.target_default:
            self.differ(f"the default branch is {named}, planned {self.target_default}")
        elif self.target_default != self.default:
            self.notes.append(
                f"default branch {self.default} of the source is {self.target_default} in the"
                " target, as planned"
            )
        source = git(
            self.mirror, "rev-list", "--first-parent", "--reverse", f"refs/heads/{self.default}"
        ).split()
        branch = self.target_default
        target = git(
            work, "rev-list", "--first-parent", "--reverse", f"refs/heads/{branch}"
        ).split()
        steps = []
        for e in self.events:
            if e["kind"] == "push-commits":
                steps += [("commit", c) for c in e["commits"]]
            elif e["kind"] == "merge-pull":
                steps.append(("merge", e))
        self.totals.append((f"commits on {branch}", len(target)))
        if not len(source) == len(target) == len(steps):
            self.differ(
                f"{branch} has {len(target)} first-parent commits, the source {len(source)},"
                f" the event file {len(steps)}"
            )
            return
        src = read_commits(self.mirror, source)
        tgt = read_commits(work, target)
        host = info["html_url"].rsplit("/", 2)[0]
        authors = set()
        for i, ((kind, step), s, t) in enumerate(zip(steps, source, target, strict=True), 1):
            at = f"{branch}, step {i} ({t[:7]})"
            planned_sha = step["sha"] if kind == "commit" else step["source_commit"]
            if planned_sha != s:
                self.differ(f"{at}: the event file plans {planned_sha[:7]}, the source has {s[:7]}")
            if self.hashes.get(s) != t:
                recorded = self.hashes.get(s, "nothing")[:7]
                self.differ(f"{at}: the state file records {recorded} for {s[:7]}, not this commit")
            if tgt[t]["tree"] != src[s]["tree"]:
                self.differ(f"{at}: tree {tgt[t]['tree'][:7]}, the source's {src[s]['tree'][:7]}")
            message = tgt[t]["message"]
            lines = [x.lower() for x in message.splitlines() if CO_AUTHOR.match(x)]
            if len(lines) != len(set(lines)):
                self.differ(f"{at}: a Co-authored-by line stands twice")
            if kind == "commit":
                if message != self.text(step["message"]):
                    self.differ(
                        f"{at}: the message differs;"
                        f" {where_texts_part(self.text(step['message']), message)}"
                    )
                for role in ("author", "committer"):
                    p, got = step[role], tgt[t][role]
                    date = git_date(p["date"])
                    if role == "committer" and self.committer_dates is not None:
                        date = self.committer_dates.get(s, "no date in the state file")
                    want = {"name": p["name"], "email": p["email"], "date": date}
                    if got != want:
                        self.differ(
                            f"{at}: {role} {got['name']} <{got.get('email')}> {got.get('date')},"
                            f" planned {want['name']} <{want['email']}> {want['date']}"
                        )
                continue
            n = step["number"]
            url = f"{host}/{self.final_name}/pull/{n}" if self.final_name else self.urls.get(n)
            body = self.text(step["commit_message"]).replace("{pr_url}", str(url))
            planned = self.text(step["commit_title"]) + (f"\n\n{body}" if body else "")
            if without_added_trailers(message, planned) != planned.rstrip("\n"):
                self.differ(
                    f"{at}: the message of #{n} differs; {where_texts_part(planned, message)}"
                )
            if tgt[t]["committer"].get("email") != "noreply@github.com":
                self.differ(f"{at}: the merge of #{n} is committed by {tgt[t]['committer']}")
            authors.add(f"{tgt[t]['author']['name']} <{tgt[t]['author'].get('email')}>")
        if authors:
            self.notes.append(f"merges authored by {', '.join(sorted(authors))}")

    def recreated(self, work):
        pairs = sorted(self.hashes.items())
        query = "".join(f"{x}^{{tree}}\n" for pair in pairs for x in pair)
        out = git(work, "cat-file", "--batch-check=%(objectname)", stdin=query).splitlines()
        for i, (s, t) in enumerate(pairs):
            source_tree, target_tree = out[2 * i], out[2 * i + 1]
            if target_tree.endswith(" missing"):
                self.differ(f"the recreated commit {t[:7]} of {s[:7]} is not in the target")
            elif source_tree != target_tree:
                self.differ(f"the recreated commit {t[:7]} has another tree than {s[:7]}")
        planned = [c["sha"] for e in self.events for c in e.get("commits", [])]
        planned += [e["source_commit"] for e in self.events if e["kind"] == "merge-pull"]
        for sha in planned:
            if sha not in self.hashes:
                self.differ(f"the state file records no recreated commit for {sha[:7]}")
        self.totals.append(("recreated commits", len(pairs)))
        if self.committer_dates is not None:
            self.committed_in_order(
                work, [c["sha"] for e in self.events for c in e.get("commits", [])]
            )

    def committed_in_order(self, work, sources):
        # A rebase can commit a commit before its parent.
        pairs = [(s, self.hashes[s]) for s in sources if s in self.hashes]
        found = read_commits(work, [sha for _, sha in pairs])
        parents = sorted({p for _, sha in pairs if sha in found for p in found[sha]["parents"]})
        dates = {**found, **read_commits(work, parents)}

        def seconds(sha):
            return int(dates[sha]["committer"]["date"].split()[0])

        for source, sha in pairs:
            if sha not in found:
                continue
            for parent in found[sha]["parents"]:
                if parent in dates and seconds(sha) < seconds(parent):
                    self.differ(
                        f"the recreated commit {sha[:7]} of {source[:7]} is committed before its"
                        f" parent {parent[:7]}"
                    )

    def branches(self, refs, info):
        found = {
            ref[len("refs/heads/") :]: sha
            for ref, sha in refs.items()
            if ref.startswith("refs/heads/")
        }
        merged = {e["number"] for e in self.events if e["kind"] == "merge-pull"}
        deletes = bool(info.get("delete_branch_on_merge"))
        expected = {self.target_default}
        for e in self.events:
            if e["kind"] != "push-branch" or (deletes and e["number"] in merged):
                continue
            expected.add(e["branch"])
            sha = found.get(e["branch"])
            if sha and sha != self.heads.get(e["number"]):
                self.differ(
                    f"branch {e['branch']} is at {sha[:7]}, the state file's"
                    f" {self.heads.get(e['number'], '?')[:7]}"
                )
        for name in sorted(expected - set(found)):
            self.differ(f"branch {name} is missing in the target")
        for name in sorted(set(found) - expected):
            self.differ(f"branch {name} is in the target, but in no event")
        source = git(self.mirror, "for-each-ref", "--format=%(refname:short)", "refs/heads/")
        names = {self.target_default if x == self.default else x for x in source.split("\n")}
        for name in sorted(set(found) - names):
            self.notes.append(f"branch {name} stays in the target; the source no longer has it")
        self.totals.append(("branches", len(found)))

    def carried_tag(self, work, refs, e):
        name, want = e["name"], self.hashes.get(e["commit"])
        ref = f"refs/tags/{name}"
        found = refs.get(ref)
        if found is None:
            self.differ(f"tag {name} of the source is missing in the target")
            return
        if found != want:
            recreated = f"the recreated {want[:7]}" if want else "a recreated commit"
            self.differ(
                f"tag {name} of the source is at {found[:7]} in the target, not at {recreated}"
            )
        kind = git(work, "cat-file", "-t", ref).strip()
        planned = "annotated" if e["annotated"] else "lightweight"
        if (kind == "tag") != e["annotated"]:
            got = "annotated" if kind == "tag" else "lightweight"
            self.differ(f"tag {name} is {got} in the target, {planned} as planned")
            return
        if not e["annotated"]:
            return
        head, _, message = git(work, "cat-file", "tag", ref).partition("\n\n")
        fields = dict(line.split(" ", 1) for line in head.split("\n") if " " in line)
        if fields.get("type") != "commit":
            self.differ(f"tag {name} names a {fields.get('type')} in the target, not a commit")
        expected, got = self.text(e["message"]), unsigned(message)
        if got != message and expected and not expected.endswith("\n"):
            # The run ends such a message with a line break before it signs
            # it, since verify-tag finds a signature only at a line's start.
            expected += "\n"
        if got != expected:
            self.differ(f"tag {name}: the message differs; {where_texts_part(expected, got)}")
        t = e["tagger"]
        want_tagger = {"name": t["name"], "email": t["email"], "date": git_date(t["date"])}
        match = IDENTITY.match(fields.get("tagger", ""))
        got = match.groupdict() if match else {"name": fields.get("tagger"), "email": None}
        if got != want_tagger:
            self.differ(
                f"tag {name}: tagger {got['name']} <{got.get('email')}> {got.get('date')},"
                f" planned {t['name']} <{t['email']}> {want_tagger['date']}"
            )

    def left_behind(self, work, refs, source_releases, target_releases):
        if "left_behind" not in self.header:
            self.notes.append(
                "the event file predates left_behind: it accepts nothing as left behind"
            )
        left = {(x["kind"], x["name"]) for x in self.header.get("left_behind", [])}
        # The target of each pushed branch, which branches() checks already.
        pushed = {
            e["branch"]: self.heads.get(e["number"])
            for e in self.events
            if e["kind"] == "push-branch"
        }

        def off(kind):
            return f"{kind}s" in self.turned_off and kind in ("tag", "release")

        def lacks(kind, name, what):
            if off(kind):
                self.notes.append(
                    f"{kind} {name} of the source is left behind: {kind}s are turned off"
                )
            elif (kind, name) in left:
                self.notes.append(f"{kind} {name} of the source is left behind, as planned")
            else:
                self.differ(f"{kind} {name} of the source {what}")

        planned = {e["name"]: e for e in self.events if e["kind"] == "create-tag"}
        source = peeled_refs(self.mirror, "refs/heads/", "refs/tags/")
        for ref, sha in sorted(source.items()):
            kind = "branch" if ref.startswith("refs/heads/") else "tag"
            name = ref.split("/", 2)[2]
            if kind == "branch" and name == self.default:
                continue
            if kind == "tag" and name in planned:
                self.carried_tag(work, refs, planned.pop(name))
                continue
            found, want = refs.get(ref), self.hashes.get(sha)
            carried = kind == "branch" and want is not None and pushed.get(name) == want
            if carried and (kind, name) not in left:
                continue
            if found is None:
                lacks(kind, name, "is missing in the target")
            elif off(kind):
                self.differ(f"{kind} {name} is in the target, though {kind}s are turned off")
            elif found != want:
                recreated = f"the recreated {want[:7]}" if want else "a recreated commit"
                lacks(kind, name, f"is at {found[:7]} in the target, not at {recreated}")
        for name in sorted(planned):
            self.differ(f"tag {name} is in the event file, but the mirror lacks it")
        tags = sorted(r for r in refs if r.startswith("refs/tags/"))
        for ref in tags:
            if ref not in source:
                self.differ(f"tag {ref[len('refs/tags/') :]} is in the target, not in the source")
        # A draft and a published release may share a tag, so a carried release is
        # found by its ids in the event and state files, any other by its tag.
        source_by = {r["id"]: r for r in source_releases}
        target_by = {r["id"]: r for r in target_releases}
        carried = [e for e in self.events if e["kind"] == "create-release"]
        latest = None
        if carried:
            # GitHub answers 404 where a repository has no release.
            latest = (gh_found(f"repos/{self.slug}/releases/latest") or {}).get("id")
        assets, matched = 0, set()
        for e in carried:
            at = release_label(e, carried)
            record = self.releases.get(str(e["release_id"])) or {}
            s, t = source_by.pop(e["release_id"], None), target_by.pop(record.get("id"), None)
            if s is None:
                self.differ(f"{at} is in the event file, but the source lacks it")
            elif t is None:
                self.differ(f"{at} of the source is missing in the target")
            else:
                assets += self.carried_release(e, s, t, latest, at)
        others = {}
        for t in target_by.values():
            others.setdefault(t["tag_name"], []).append(t)
        for s in sorted(source_by.values(), key=lambda r: (r["tag_name"], r["id"])):
            name = s["tag_name"]
            if not others.get(name):
                lacks("release", name, "is missing in the target")
                continue
            matched.add(others[name].pop(0)["id"])
            if off("release"):
                self.differ(f"release {name} is in the target, though releases are turned off")
        for t in sorted(target_by.values(), key=lambda r: (r["tag_name"], r["id"])):
            if t["id"] not in matched:
                self.differ(f"release {t['tag_name']} is in the target, not in the source")
        self.totals += [
            ("tags", len(tags)),
            ("releases", len(target_releases)),
            ("release assets", assets),
        ]

    def carried_release(self, e, source, target, latest, at):
        if (target.get("name") or "") != e["name"]:
            self.differ(f"{at}: name {target.get('name')!r}, planned {e['name']!r}")
        expected = self.expected_text(e["body"], e["published_at"] or e["created_at"])
        found = target.get("body") or ""
        if found != expected:
            self.differ(f"{at}: the body differs; {where_texts_part(expected, found)}")
        for field, label in (("draft", "draft"), ("prerelease", "pre-release")):
            if bool(target.get(field)) != e[field]:
                got, planned = (str(x).lower() for x in (bool(target.get(field)), e[field]))
                self.differ(f"{at}: {label} {got}, planned {planned}")
        if (latest == target["id"]) != e["latest"]:
            self.differ(
                f"{at}: latest {str(not e['latest']).lower()}, planned {str(e['latest']).lower()}"
            )
        want = {
            a["name"]: a
            for a in gh_pages(f"repos/{self.source}/releases/{source['id']}/assets")
            if a.get("state", "uploaded") == "uploaded"
        }
        got = {a["name"]: a for a in gh_pages(f"repos/{self.slug}/releases/{target['id']}/assets")}
        for name in sorted(set(want) | set(got)):
            w, g = want.get(name), got.get(name)
            if g is None:
                self.differ(f"{at}: asset {name} is missing in the target")
                continue
            if w is None:
                self.differ(f"{at}: asset {name} is in the target, not in the source")
                continue
            if g.get("state", "uploaded") != "uploaded":
                self.differ(f"{at}: asset {name} is {g['state']} in the target, not uploaded")
            for field, label in (
                ("size", "size"),
                ("content_type", "content type"),
                ("digest", "digest"),
            ):
                if None not in (w.get(field), g.get(field)) and w[field] != g[field]:
                    self.differ(f"{at}: asset {name}: {label} {g[field]}, the source's {w[field]}")
        return len(got)

    def compare(self):
        target_info = gh_get(f"repos/{self.slug}")
        if str(target_info.get("full_name", "")).lower() != self.slug.lower():
            raise CompareError(
                f"GitHub answers for {self.slug} with {target_info.get('full_name')}; name that one"
            )
        self.items(
            {i["number"]: i for i in gh_pages(f"repos/{self.source}/issues?state=all")},
            {i["number"]: i for i in gh_pages(f"repos/{self.slug}/issues?state=all")},
        )
        self.labels(gh_pages(f"repos/{self.source}/labels"), gh_pages(f"repos/{self.slug}/labels"))
        self.comments(
            gh_pages(f"repos/{self.source}/issues/comments"),
            gh_pages(f"repos/{self.slug}/issues/comments"),
            self.source_reviews(),
        )
        self.totals.append(("texts with a replaced hash", self.replaced))
        with tempfile.TemporaryDirectory(prefix="compare-replay-") as folder:
            work = Path(folder) / "target.git"
            refs = self.fetch(work, target_info)
            self.main_branch(work, target_info)
            self.recreated(work)
            self.branches(refs, target_info)
            self.pull_heads(refs)
            self.left_behind(
                work,
                refs,
                gh_pages(f"repos/{self.source}/releases"),
                gh_pages(f"repos/{self.slug}/releases"),
            )

        print(f"Compared {self.source} with {self.slug}:")
        for name, value in self.totals:
            print(f"  {name:<27}{value:>6}")
        if self.notes:
            print("Notes:")
            for note in self.notes:
                print(f"  {note}")
        if not self.differences:
            print("No differences")
            return 0
        print(f"Differences: {len(self.differences)}")
        for difference in self.differences:
            print(f"  {difference}")
        return 1


def main(argv):
    if argv[:1] in (["-h"], ["--help"]):
        usage(0)
    state, with_times = None, False
    while argv[:1] and argv[0].startswith("--"):
        option, argv = argv[0], argv[1:]
        if option == "--state" and argv:
            state, argv = Path(argv[0]), argv[1:]
        elif option == "--with-times":
            with_times = True
        else:
            usage()
    if len(argv) != 3 or argv[0].startswith("-") or not SLUG.fullmatch(argv[2]):
        usage()
    events_path, mirror, slug = Path(argv[0]), Path(argv[1]), argv[2]
    try:
        if not events_path.is_file():
            raise CompareError(f"no event file at {events_path}")
        if not mirror.is_dir():
            raise CompareError(f"no mirror at {mirror}")
        state = state or default_state_path(events_path)
        return Comparison(events_path, mirror, slug, state, with_times).compare()
    except CompareError as stop:
        print(f"{PROG}: {stop}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
