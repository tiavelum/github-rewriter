def test_creates_each_release_on_its_tag_with_its_name_body_kind_latest_and_assets(
    api, hashes, replay_x
):
    """run-replay.py creates each release on its tag, the pre-release and the draft included, in a target with immutable releases, with the planned name, the body with its hashes replaced, the source's latest as the latest, and each asset of the source whole"""  # noqa: E501 # the description word for word
    target = replay_x.target
    m = json.loads(replay_x.state.read_text(encoding="utf-8"))["hashes"]
    r = releases_by_tag(target)
    assert r
    assert sorted(r) == ["v0.1.1", "v0.2", "v0.3"]
    assert [
        (r[t]["draft"], r[t]["prerelease"], r[t]["latest"]) for t in ("v0.2", "v0.1.1", "v0.3")
    ] == [
        (False, False, True),
        (False, True, False),
        (True, False, False),
    ]
    v02 = r["v0.2"]
    assert (v02["name"], v02["body"], v02["target_commitish"]) == (
        "Second",
        "Built from " + m[hashes["C4"]][:7] + ".",
        m[hashes["C5"]],
    )
    assert m[hashes["C4"]][:7] != hashes["C4"][:7]
    assert r["v0.3"]["target_commitish"] == "main"
    assert [(a["name"], a["label"], a["content_type"], a["state"]) for a in v02["assets"]] == [
        ("tool.tar.gz", "", "application/gzip", "uploaded"),
        ("notes.txt", "Release notes", "text/plain", "uploaded"),
    ]
    assert [asset_bytes(target, a) for a in v02["assets"]] == [
        (api / f"{RELEASES}_assets_{i}.bin").read_bytes() for i in ("11", "12")
    ]
    assert target.git("tag", "-l") == "v0.1\nv0.1.1\nv0.2"


