@pytest.fixture(scope="module")
def compare_diff(root, base_env, source, run_plan, replay_uninterrupted, compare_finished, compare):
    """The copy of the uninterrupted replay's target, made after its
    comparison: #4 closed as completed, a footer on the last comment, the
    colour of a label, a missing branch, the head of #3 at another commit,
    and a last commit on main with the tree of the one before; compared."""
    target = copy_target(root, replay_uninterrupted.target, "gh-diff")
    folder = target.folder

    def footer(comments):
        comments[-1].update(
            body=comments[-1]["body"]
            + "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        )

    def colour(labels):
        for x in labels:
            if x["name"] == "bug":
                x.update(color="ee0701")

    edit_json(folder / "items.json", lambda items: items["4"].update(state_reason="completed"))
    edit_json(folder / "comments.json", footer)
    edit_json(folder / "labels.json", colour)
    target.git("update-ref", "-d", "refs/heads/fix/3-parser")
    target.git("update-ref", "refs/pull/3/head", "main~1")
    made = run(
        ["git", "--git-dir", target.repo, "commit-tree", "main~1^{tree}", "-p", "main~1"],
        base_env,
        root,
        stdin="same tree\n",
    )
    assert made.status == 0, made.err
    target.git("update-ref", "refs/heads/main", made.out.strip())
    tail = (run_plan.file, source.mirror, TOOL_NEW)
    return compare(target, "--state", replay_uninterrupted.state, *tail, api=run_plan.api)


