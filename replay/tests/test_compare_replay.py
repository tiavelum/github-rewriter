    target = copy_target(root, replay_uninterrupted.target, "gh-diff")
    folder = target.folder

    def footer(comments):
        comments[-1].update(
            body=comments[-1]["body"]
            + "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        )

    def colour(labels):
        for x in labels:
            if x["name"] == "bug":
                x.update(color="ee0701")

