def test_creates_each_tag_at_the_recreated_commit_with_its_message_tagger_and_date_unsigned(
    hashes, replay_tags_releases
):
    """run-replay.py creates each tag at the recreated commit, lightweight or annotated, with the planned message, its hashes replaced, the mapped tagger and the original date, unsigned"""  # noqa: E501 # the description word for word
    git = replay_tags_releases.target.git
    state = json.loads(replay_tags_releases.state.read_text(encoding="utf-8"))
    m = state["hashes"]
    assert git("cat-file", "-t", "refs/tags/v0.1") == "commit"
    assert git("rev-parse", "refs/tags/v0.1") == m[hashes["M2"]]
    assert git("cat-file", "-t", "refs/tags/v0.2") == "tag"
    assert git("cat-file", "tag", "refs/tags/v0.2").split("\n") == [
        "object " + m[hashes["C5"]],
        "type commit",
        "tag v0.2",
        "tagger Ada Example <ada@example.com> 1772888400 +0200",
        "",
        "Second, after " + m[hashes["C4"]][:7],
    ]
    assert m[hashes["C4"]][:7] != hashes["C4"][:7]
    assert git("cat-file", "tag", "refs/tags/v0.1.1").split("\n")[:4] == [
        "object " + m[hashes["F1"]],
        "type commit",
        "tag v0.1.1",
        "tagger Bob Example <bob@example.com> 1772620200 +0000",
    ]
    assert state["tags"] == {
        "v0.1": m[hashes["M2"]],
        "v0.1.1": git("rev-parse", "refs/tags/v0.1.1"),
        "v0.2": git("rev-parse", "refs/tags/v0.2"),
    }


def test_counts_the_tags_in_its_totals_and_prints_a_line_per_tag(
    replay_tags_releases, replay_uninterrupted
):
    """run-replay.py counts the tags in its totals and prints a line per tag"""
    m2 = replay_tags_releases.target.git("rev-parse", "refs/tags/v0.1")[:7]
    out, plain = replay_tags_releases.result.out_lines, replay_uninterrupted.result.out_lines
    assert has_match("  tags +3", out), replay_tags_releases.result.out
    lightweight = rf"^ *[0-9]+/[0-9]+  create-tag    v0\.1, lightweight, at {m2}$"
    assert has_search(lightweight, out), replay_tags_releases.result.out
    annotated = r"^ *[0-9]+/[0-9]+  create-tag    v0\.2, annotated, at [0-9a-f]{7}$"
    assert has_search(annotated, out), replay_tags_releases.result.out
    assert has_match("  create-tag +3", out), replay_tags_releases.result.out
    assert has_match("  create-tag +0", plain), replay_uninterrupted.result.out
